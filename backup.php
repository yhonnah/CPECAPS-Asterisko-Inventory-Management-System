<?php
require 'db.php';
require 'authguard.php';

// Accessible only to Admin and Owner
requireRole(['Admin', 'Owner'], $pdo);

$username = $_SESSION['username'];
$role = $_SESSION['role'];
$message = '';
$messageType = '';
$backupDir = __DIR__ . '/backups/';

if (!is_dir($backupDir)) {
    mkdir($backupDir, 0755, true);
}

// Handle Direct Download Request
if (isset($_GET['download'])) {
    $filename = basename($_GET['download']);
    $filepath = $backupDir . $filename;
    if (file_exists($filepath) && pathinfo($filepath, PATHINFO_EXTENSION) === 'sql') {
        header('Content-Type: application/sql');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . filesize($filepath));
        readfile($filepath);
        exit;
    }
}

// Handle Trigger Backup Action
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action'])) {
    validateCsrfToken();
    $action = $_POST['action'];

    if ($action === 'trigger_backup') {
        try {
            $timestamp = date('Ymd_His');
            $filename = "asterisko_backup_{$timestamp}.sql";
            $filepath = $backupDir . $filename;

            $tables = [
                'users',
                'suppliers',
                'stock_items',
                'supplier_mappings',
                'audit_logs',
                'purchase_orders',
                'purchase_order_items',
                'invoice_drafts',
                'sales_records',
                'database_backups'
            ];

            $sqlContent = "-- Asterisko Inventory System Automated SQL Backup\n";
            $sqlContent .= "-- Timestamp: " . date('Y-m-d H:i:s') . "\n";
            $sqlContent .= "-- Generated by: {$username}\n";
            $sqlContent .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\nSTART TRANSACTION;\nSET time_zone = \"+00:00\";\n\n";

            foreach ($tables as $table) {
                // Check if table exists
                $tableCheck = $pdo->query("SHOW TABLES LIKE '$table'")->fetch();
                if (!$tableCheck) continue;

                $sqlContent .= "-- --------------------------------------------------------\n";
                $sqlContent .= "-- Table structure for `$table`\n--\n";
                $sqlContent .= "DROP TABLE IF EXISTS `$table`;\n";
                $create = $pdo->query("SHOW CREATE TABLE `$table`")->fetch(PDO::FETCH_ASSOC);
                $sqlContent .= $create['Create Table'] . ";\n\n";

                // Table Rows
                $rows = $pdo->query("SELECT * FROM `$table`")->fetchAll(PDO::FETCH_ASSOC);
                if (!empty($rows)) {
                    $sqlContent .= "-- Dumping data for `$table`\n--\n";
                    $cols = array_keys($rows[0]);
                    $colList = implode('`, `', $cols);
                    $sqlContent .= "INSERT INTO `$table` (`$colList`) VALUES\n";
                    $valList = [];
                    foreach ($rows as $r) {
                        $rowVals = [];
                        foreach ($r as $val) {
                            if ($val === null) {
                                $rowVals[] = "NULL";
                            } else {
                                $rowVals[] = $pdo->quote($val);
                            }
                        }
                        $valList[] = "(" . implode(', ', $rowVals) . ")";
                    }
                    $sqlContent .= implode(",\n", $valList) . ";\n\n";
                }
            }
            $sqlContent .= "COMMIT;\n";

            // Save to disk
            file_put_contents($filepath, $sqlContent);
            $fileSizeBytes = filesize($filepath);

            // Record in database_backups
            $stmt = $pdo->prepare("INSERT INTO database_backups (filename, file_size_bytes, created_by) VALUES (?, ?, ?)");
            $stmt->execute([$filename, $fileSizeBytes, $username]);

            // Audit the backup action
            $audit = $pdo->prepare("INSERT INTO audit_logs (item_id, previous_value, new_value, change_type, reason, acting_user) VALUES (NULL, NULL, NULL, 'db_backup', ?, ?)");
            $audit->execute(["Database backup compiled ({$filename}, " . round($fileSizeBytes / 1024, 2) . " KB)", $username]);

            // Retain the 7 most recent backups
            $allBackups = $pdo->query("SELECT * FROM database_backups ORDER BY created_at DESC")->fetchAll(PDO::FETCH_ASSOC);
            if (count($allBackups) > 7) {
                $toDelete = array_slice($allBackups, 7);
                foreach ($toDelete as $old) {
                    $oldPath = $backupDir . $old['filename'];
                    if (file_exists($oldPath)) {
                        unlink($oldPath);
                    }
                    $pdo->prepare("DELETE FROM database_backups WHERE id = ?")->execute([$old['id']]);
                }
            }

            $message = "Database backup '{$filename}' generated and stored successfully (Size: " . round($fileSizeBytes / 1024, 2) . " KB).";
            $messageType = 'success';
        } catch (Exception $e) {
            $message = "Backup error: " . $e->getMessage();
            $messageType = 'error';
        }
    }
}

// Fetch backup records
