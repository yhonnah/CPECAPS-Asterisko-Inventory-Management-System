                    </div>
                </div>
            </div>

            <!-- Backups Table Card -->
            <div class="bg-white dark:bg-[#0C2340] rounded-2xl shadow-sm border border-slate-200/80 dark:border-[#15345C] overflow-hidden">
                <div class="p-5 border-b border-slate-200 dark:border-[#15345C]">
                    <h2 class="font-bold text-base text-slate-900 dark:text-white">Backup Snapshot Archive</h2>
                    <p class="text-xs text-slate-500 dark:text-slate-400">Downloadable SQL files containing complete DDL schemas and table records.</p>
