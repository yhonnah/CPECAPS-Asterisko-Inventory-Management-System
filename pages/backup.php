                        </thead>
                        <tbody>
                            <?php if (count($backups) === 0): ?>
                                <tr>
                                    <td colspan="5" class="text-center py-8 text-slate-400">No database snapshots generated yet. Click "+ Backup Database Now" above.</td>
                                </tr>
                            <?php else: ?>
                                <?php foreach ($backups as $b): ?>
                                <tr>
                                    <td class="font-mono font-bold text-slate-900 dark:text-white"><?= htmlspecialchars($b['filename']) ?></td>
                                    <td class="font-mono font-semibold"><?= round($b['file_size_bytes'] / 1024, 2) ?> KB</td>
