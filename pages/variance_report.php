require_once __DIR__ . '/../config/db.php';
require_once __DIR__ . '/../includes/authguard.php';

// Accessible by Admin/Manager and Owner
requireRole(['Admin', 'Owner'], $pdo);

$username = $_SESSION['username'];
$role = $_SESSION['role'];

// Date range filters (default to current month)
$startDate = $_GET['start_date'] ?? date('Y-m-01');
$endDate = $_GET['end_date'] ?? date('Y-m-d');
$selectedItemId = !empty($_GET['item_id']) ? (int)$_GET['item_id'] : 0;

$query = "
    SELECT al.*, si.name AS item_name, si.unit, si.category
    FROM audit_logs al
    JOIN stock_items si ON si.id = al.item_id
    WHERE al.change_type = 'count_correction'
      AND (al.previous_value != al.new_value)
      AND DATE(al.created_at) BETWEEN ? AND ?
";
$params = [$startDate, $endDate];

if ($selectedItemId > 0) {
    $query .= " AND al.item_id = ?";
    $params[] = $selectedItemId;
}

$query .= " ORDER BY al.created_at DESC";

$stmt = $pdo->prepare($query);
$stmt->execute($params);
$variances = $stmt->fetchAll(PDO::FETCH_ASSOC);

// Fetch items for filter dropdown
$stockItems = $pdo->query("SELECT id, NAME, NAME AS name FROM stock_items ORDER BY NAME")->fetchAll(PDO::FETCH_ASSOC);

// Summary stats
$totalShortages = 0;
$totalSurpluses = 0;
foreach ($variances as $v) {
    $diff = (float)$v['new_value'] - (float)$v['previous_value'];
    if ($diff < 0) {
        $totalShortages++;
    } elseif ($diff > 0) {
        $totalSurpluses++;
    }
}

// Handle CSV Export
if (isset($_GET['export']) && $_GET['export'] === 'csv') {
    $filename = "Asterisko_Variance_Report_{$startDate}_to_{$endDate}.csv";
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    $out = fopen('php://output', 'w');
    fprintf($out, chr(0xEF).chr(0xBB).chr(0xBF)); // UTF-8 BOM

    fputcsv($out, ['Asterisko Artisan Coffee - Stock Count Variance Audit Report']);
    fputcsv($out, ['Filter Period:', "{$startDate} to {$endDate}"]);
    fputcsv($out, ['Generated On:', date('Y-m-d H:i:s'), 'Generated By:', $username]);
    fputcsv($out, ['Total Discrepancies:', count($variances), 'Shortages:', $totalShortages, 'Surpluses:', $totalSurpluses]);
    fputcsv($out, []);

    fputcsv($out, ['Timestamp', 'Item Name', 'Category', 'Recorded Stock', 'Physical Count', 'Variance', 'Unit', 'Discrepancy Type', 'Auditor / Barista', 'Reason / Notes']);
    foreach ($variances as $v) {
        $diff = (float)$v['new_value'] - (float)$v['previous_value'];
        $type = $diff < 0 ? 'Shortage' : ($diff > 0 ? 'Surplus' : 'Matched');
        fputcsv($out, [
            $v['created_at'],
            $v['item_name'],
            $v['category'],
            $v['previous_value'],
            $v['new_value'],
            ($diff > 0 ? "+{$diff}" : $diff),
            $v['unit'],
            $type,
            $v['acting_user'],
            $v['reason']
        ]);
    }
    fclose($out);
    exit;
}

